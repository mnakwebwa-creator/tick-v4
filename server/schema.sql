-- Tick — schema (PostgreSQL). Safe to run more than once.
-- The same file is used by Netlify Database (netlify/database/migrations) and by the local server.

CREATE TABLE IF NOT EXISTS users (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      text NOT NULL UNIQUE,
  full_name     text NOT NULL,
  password_hash text NOT NULL,
  role          text NOT NULL DEFAULT 'teacher' CHECK (role IN ('admin', 'teacher')),
  status        text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'pending', 'suspended'))
);

CREATE TABLE IF NOT EXISTS classes (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          text NOT NULL,
  academic_year integer NOT NULL,
  teacher_id    integer REFERENCES users(id),
  status        text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'archived'))
);
-- No two active classes with the same name in one year
CREATE UNIQUE INDEX IF NOT EXISTS classes_active_name
  ON classes (lower(name), academic_year) WHERE status = 'active';

CREATE TABLE IF NOT EXISTS learners (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_number text NOT NULL UNIQUE,
  full_name      text NOT NULL,
  class_id       integer NOT NULL REFERENCES classes(id),
  consent        boolean NOT NULL DEFAULT false, -- guardian authorization for face enrollment
  status         text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive'))
);
CREATE INDEX IF NOT EXISTS learners_class ON learners (class_id);

-- Encrypted embeddings only; photos never reach the server
CREATE TABLE IF NOT EXISTS face_templates (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  learner_id    integer NOT NULL REFERENCES learners(id),
  template_data text NOT NULL,
  model_version text NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT now(),
  revoked_at    timestamptz
);
CREATE INDEX IF NOT EXISTS face_templates_learner ON face_templates (learner_id) WHERE revoked_at IS NULL;

CREATE TABLE IF NOT EXISTS attendance_sessions (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id     integer NOT NULL REFERENCES classes(id),
  session_date text NOT NULL CHECK (session_date ~ '^\d{4}-\d{2}-\d{2}$'), -- school's local date
  session_type text NOT NULL DEFAULT 'Morning register',
  created_by   integer NOT NULL REFERENCES users(id),
  UNIQUE (class_id, session_date, session_type)
);

CREATE TABLE IF NOT EXISTS attendance_records (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id   integer NOT NULL REFERENCES attendance_sessions(id),
  learner_id   integer NOT NULL REFERENCES learners(id),
  status       text NOT NULL CHECK (status IN ('present', 'absent')),
  method       text NOT NULL CHECK (method IN ('face', 'manual')),
  similarity   real,
  confirmed_by integer NOT NULL REFERENCES users(id),
  recorded_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (session_id, learner_id)
);

CREATE TABLE IF NOT EXISTS audit_log (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    integer REFERENCES users(id),
  action     text NOT NULL,
  details    jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
